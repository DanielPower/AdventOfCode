use crate::manifest::Impl;
use crate::model::{Solution, days_in_year, parts_for_day};
use crate::results::{Status, Store};
use anyhow::{Context, Result, bail};
use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

pub const START: &str = "<!-- aoc:progress:start -->";
pub const END: &str = "<!-- aoc:progress:end -->";

#[derive(Clone, Copy, PartialEq, Eq)]
enum Cell {
    Both,
    OnePart,
    Failing,
    Unverified,
    Missing,
}

impl Cell {
    fn icon(self) -> &'static str {
        match self {
            Cell::Both => "✅",
            Cell::OnePart => "🟡",
            Cell::Failing => "❌",
            Cell::Unverified => "❔",
            Cell::Missing => "⬜",
        }
    }
}

fn cell(imp: &Impl, store: &Store, day: u8) -> Cell {
    let parts = parts_for_day(imp.year, day);
    let status = |part| {
        let sol = Solution { day, part };
        imp.solutions
            .contains(&sol)
            .then(|| store.get(imp, sol).map(|e| e.status))
    };
    let statuses: Vec<Option<Option<Status>>> = parts.iter().map(|&p| status(p)).collect();
    let passed = |i: usize| matches!(statuses.get(i), Some(Some(Some(Status::Pass))));
    if statuses.iter().flatten().flatten().any(|s| s.is_failure()) {
        Cell::Failing
    } else if (0..parts.len()).all(passed) {
        Cell::Both
    } else if (0..parts.len()).any(passed) {
        Cell::OnePart
    } else if statuses.iter().any(Option::is_some) {
        Cell::Unverified
    } else {
        Cell::Missing
    }
}

pub fn render(impls: &[Impl], store: &Store) -> String {
    let mut out = String::new();
    out.push_str(START);
    out.push_str("\n<!-- Generated by `cargo aoc readme` from results.json; edits inside this block are overwritten. -->\n\n");
    out.push_str(
        "✅ both parts · 🟡 one part · ❌ failing · ❔ not verified yet · ⬜ not attempted\n",
    );

    let mut by_year: BTreeMap<u16, Vec<&Impl>> = BTreeMap::new();
    for imp in impls {
        by_year.entry(imp.year).or_default().push(imp);
    }
    for (year, impls) in by_year {
        let days = days_in_year(year);
        let stars: BTreeSet<Solution> = impls
            .iter()
            .flat_map(|imp| {
                imp.solutions
                    .iter()
                    .filter(|&&s| store.get(imp, s).is_some_and(|e| e.status == Status::Pass))
                    .copied()
            })
            .collect();
        out.push_str(&format!("\n### {year} · {} ⭐\n\n", stars.len()));
        out.push_str(&format!(
            "| Implementation | Language | ⭐ | Days 1–{days} |\n| --- | --- | --- | --- |\n"
        ));
        for imp in impls {
            let row: String = (1..=days).map(|d| cell(imp, store, d).icon()).collect();
            let own = imp
                .solutions
                .iter()
                .filter(|&&s| store.get(imp, s).is_some_and(|e| e.status == Status::Pass))
                .count();
            out.push_str(&format!(
                "| {} | {} | {own} | {row} |\n",
                imp.id, imp.manifest.language
            ));
        }
    }
    out.push('\n');
    out.push_str(END);
    out
}

/// Rewrite the block in README.md. Returns whether it changed.
pub fn update(root: &Path, impls: &[Impl], store: &Store, check: bool) -> Result<bool> {
    let path = root.join("README.md");
    let text =
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let (Some(start), Some(end)) = (text.find(START), text.find(END)) else {
        bail!("README.md has no `{START}` ... `{END}` block");
    };
    if end < start {
        bail!("README.md progress markers are out of order");
    }
    let updated = format!(
        "{}{}{}",
        &text[..start],
        render(impls, store),
        &text[end + END.len()..]
    );
    let changed = updated != text;
    if changed && !check {
        std::fs::write(&path, updated)?;
    }
    Ok(changed)
}
